#!/usr/bin/env python3
"""Opt-in SMB2 fixture. Binds only loopback; never configures macOS sharing.

Run from the optional bridge's isolated .venv (impacket==0.13.0).
It exposes only generated bytes under SmokeEvidence/fixture, read-only.
"""
from pathlib import Path
import argparse
import hashlib
import hmac
import json
from datetime import datetime, timezone
from impacket.smbserver import SimpleSMBServer
from impacket import smb3structs as smb2
from impacket.ntlm import compute_lmhash, compute_nthash
from impacket.nt_errors import STATUS_ACCESS_DENIED, STATUS_INVALID_HANDLE, STATUS_LOGON_FAILURE

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--evidence', type=Path, default=root / 'SmokeEvidence')
parser.add_argument('--port', type=int, default=14455)
parser.add_argument('--normalize-error-responses', action='store_true',
                    help='Correct Impacket 0.13.0 CLOSE/session error bodies to MS-SMB2 2.2.2; preserve status and signing')
args = parser.parse_args()
if not 1024 <= args.port <= 65535:
    parser.error('Use an unprivileged loopback port')
evidence = args.evidence.resolve()
fixture = evidence / "fixture"
fixture.mkdir(parents=True, exist_ok=True)
(fixture / "fixture.bin").write_bytes(bytes(index % 251 for index in range(65_536)))
(fixture / "denied.bin").write_bytes(b"Synthetic server-denial control")
(fixture / "音频 目录").mkdir(exist_ok=True)
(fixture / "音频 目录" / "片段 一.bin").write_bytes(bytes(index % 251 for index in range(65_536)))
server = SimpleSMBServer(listenAddress="127.0.0.1", listenPort=args.port)
server.addShare("Probe", str(fixture), "Synthetic read-only resource-access fixture", readOnly="yes")
server.setSMB2Support(True)
# Public synthetic fixture credential, never a user/NAS credential.
server.addCredential("probe", 0, compute_lmhash("fixture-only"), compute_nthash("fixture-only"))
server.setLogFile(str(evidence / "server.log"))

def trace_command(code):
    original = None
    def traced(connection, backend, packet):
        requested_path = None
        if code == smb2.SMB2_CREATE:
            request = smb2.SMB2Create(packet['Data'])
            requested_path = request['Buffer'][:request['NameLength']].decode('utf-16le')
        if requested_path == 'denied.bin':
            # Explicit server refusal is a negative control, independent of local
            # filesystem ACLs. It must remain a real error after cleanup fixes.
            result = ([smb2.SMB2Error()], None, STATUS_ACCESS_DENIED)
        else:
            result = original(connection, backend, packet)
        normalized = False
        original_body = None
        if args.normalize_error_responses and (
            (code == smb2.SMB2_CLOSE and result[2] == STATUS_INVALID_HANDLE) or
            (code == smb2.SMB2_SESSION_SETUP and result[2] == STATUS_LOGON_FAILURE)
        ):
            original_body = result[0][0].__class__.__name__
            error_body = smb2.SMB2Error()
            error_body['ErrorData'] = b''
            result = ([error_body], None, result[2])
            normalized = True
        record = {"utc": datetime.now(timezone.utc).isoformat(), "event": "handler",
                  "command": code, "status": result[2], "messageID": packet['MessageID'],
                  "flags": packet['Flags'], "nextCommand": packet['NextCommand']}
        if normalized:
            record.update(normalizedErrorBody=True, originalBodyClass=original_body)
        if code == smb2.SMB2_CREATE:
            record['path'] = requested_path
        elif code == smb2.SMB2_READ:
            request = smb2.SMB2Read(packet['Data'])
            record.update(offset=request['Offset'], length=request['Length'])
        elif code == smb2.SMB2_QUERY_INFO:
            request = smb2.SMB2QueryInfo(packet['Data'])
            record.update(infoType=request['InfoType'], infoClass=request['FileInfoClass'])
        with (evidence / "protocol.jsonl").open('a') as stream:
            stream.write(json.dumps(record) + '\n')
        return result
    original = server.getServer().hookSmb2Command(code, traced)

for command in (smb2.SMB2_SESSION_SETUP, smb2.SMB2_CREATE, smb2.SMB2_QUERY_INFO, smb2.SMB2_QUERY_DIRECTORY, smb2.SMB2_READ,
                smb2.SMB2_ECHO, smb2.SMB2_CLOSE, smb2.SMB2_TREE_DISCONNECT, smb2.SMB2_LOGOFF):
    trace_command(command)

# Observe final compound responses as returned to the socket layer, rather than
# assuming that a handler's status proves successful construction or reception.
# Never log credentials, session keys, authentication payloads or audio bytes.
backend = server.getServer()
original_process_request = backend.processRequest
def traced_process_request(connection, data):
    responses = original_process_request(connection, data)
    connection_data = backend.getConnectionData(connection, False)
    session_key = connection_data.get('SigningSessionKey', b'')
    for response in responses:
        raw = response if isinstance(response, bytes) else response.getData()
        cursor = 0
        while raw[cursor:cursor + 4] == b'\xfeSMB':
            packet = smb2.SMB2Packet(raw[cursor:])
            next_command = packet['NextCommand']
            segment = raw[cursor:cursor + next_command] if next_command else raw[cursor:]
            record = {'utc': datetime.now(timezone.utc).isoformat(), 'event': 'wire-response',
                      'command': packet['Command'], 'status': packet['Status'],
                      'messageID': packet['MessageID'], 'flags': packet['Flags'],
                      'nextCommand': next_command, 'wireLength': len(segment)}
            if packet['Flags'] & smb2.SMB2_FLAGS_SIGNED and session_key:
                unsigned = segment[:48] + b'\0' * 16 + segment[64:]
                expected = hmac.new(session_key, unsigned, hashlib.sha256).digest()[:16]
                record['wireSignatureMatchesSHA256'] = hmac.compare_digest(segment[48:64], expected)
            with (evidence / 'protocol.jsonl').open('a') as stream:
                stream.write(json.dumps(record) + '\n')
            if not next_command:
                break
            cursor += next_command
    return responses
backend.processRequest = traced_process_request

print(f"Temporary SMB2 fixture: 127.0.0.1:{args.port} / Probe (synthetic bytes only)", flush=True)
try:
    server.start()
except KeyboardInterrupt:
    server.stop()
